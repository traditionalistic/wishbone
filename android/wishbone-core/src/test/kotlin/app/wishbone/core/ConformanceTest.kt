package app.wishbone.core

import kotlinx.coroutines.runBlocking
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Assumptions.assumeTrue
import org.junit.jupiter.api.DynamicTest
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.TestFactory
import java.io.File
import kotlin.math.abs

/**
 * Reads the `contract/conformance/compiled` directory's JSON files (generated by `go run ./cmd/wbc conformance`,
 * Task 3) and applies contract/README.md's harness rules to every vector, one [DynamicTest] per
 * vector name. Until that directory exists, this cleanly skips (JUnit5 assumption) instead of
 * failing — see core-decisions.md.
 */
class ConformanceTest {

    /** Guards against the dynamic factory silently collecting 0 tests (e.g. an empty/missing file passes vacuously). */
    @Test
    fun `all five compiled vector files exist and are non-empty`() {
        val dir = RepoPaths.conformanceCompiledDir
        assumeTrue(dir.isDirectory, "${dir.path} does not exist yet — skipping until the compiler produces it")
        for (name in listOf("expr.json", "format.json", "handlers.json", "events.json", "timelines.json")) {
            val file = File(dir, name)
            assertTrue(file.isFile, "missing $file")
            val count = Json.parseToJsonElement(file.readText()).jsonArray.size
            assertTrue(count > 0, "$file has no vectors")
        }
    }

    @TestFactory
    fun conformance(): List<DynamicTest> {
        val dir = RepoPaths.conformanceCompiledDir
        if (!dir.isDirectory) {
            return listOf(
                DynamicTest.dynamicTest("compiled vectors not generated yet") {
                    assumeTrue(
                        false,
                        "${dir.path} does not exist yet (generated by `go run ./cmd/wbc conformance`, Task 3) — skipping",
                    )
                },
            )
        }
        val files = dir.listFiles { f -> f.extension == "json" && f.name != "errors.json" }?.sortedBy { it.name }
            ?: emptyList()
        return files.flatMap { file -> vectorsIn(file) }
    }

    private fun vectorsIn(file: File): List<DynamicTest> {
        val arr = Json.parseToJsonElement(file.readText()).jsonArray
        return arr.map { el ->
            val obj = el.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            DynamicTest.dynamicTest("${file.name}/$name") { runVector(obj) }
        }
    }

    private fun runVector(obj: JsonObject): Unit = runBlocking {
        when (val kind = obj["kind"]!!.jsonPrimitive.content) {
            "expr" -> runExprVector(obj)
            "handler" -> runHandlerOrEventVector(obj, isEvent = false)
            "event" -> runHandlerOrEventVector(obj, isEvent = true)
            "timeline" -> runTimelineVector(obj)
            else -> assumeTrue(false, "unknown vector kind: $kind")
        }
    }

    private fun vectorMaps(obj: JsonObject): ScopeInputs {
        val document = Document.decode(obj["document"]!!.jsonObject)
        val env = (obj["env"] as? JsonObject)?.mapValues { (_, v) -> Value.fromJson(v) } ?: DEFAULT_ENV
        val data = (obj["data"] as? JsonObject)?.mapValues { (_, v) -> Value.fromJson(v) } ?: emptyMap()
        val params = (obj["params"] as? JsonObject)?.mapValues { (_, v) -> Value.fromJson(v) } ?: emptyMap()
        val stateOverrides = (obj["state"] as? JsonObject)?.mapValues { (_, v) -> Value.fromJson(v) } ?: emptyMap()
        return ScopeInputs(document, env, data, params, stateOverrides)
    }

    private data class ScopeInputs(
        val document: Document,
        val env: Map<String, Value>,
        val data: Map<String, Value>,
        val params: Map<String, Value>,
        val stateOverrides: Map<String, Value>,
    )

    private suspend fun runExprVector(obj: JsonObject) {
        val inputs = vectorMaps(obj)
        val (_, interp) = MapScope.create(inputs.document, inputs.data, inputs.params, inputs.env, inputs.stateOverrides)
        val actual = interp.eval(Expr.decode(obj["expr"]!!), null)
        val expect = Value.fromJson(obj["expect"]!!)
        assertTrue(deepEqualsWithTolerance(actual, expect), "expected $expect, got $actual")
    }

    private suspend fun runHandlerOrEventVector(obj: JsonObject, isEvent: Boolean) {
        val inputs = vectorMaps(obj)
        val calls = (obj["calls"] as? JsonObject)?.mapValues { (_, v) -> Value.fromJson(v) } ?: emptyMap()
        val sink = RecordingEffectSink(calls)
        val (scope, interp) = MapScope.create(inputs.document, inputs.data, inputs.params, inputs.env, inputs.stateOverrides, sink = sink)

        if (isEvent) {
            val nodeId = obj["node"]!!.jsonPrimitive.content
            val eventName = obj["event"]!!.jsonPrimitive.content
            val payload = Value.fromJson(obj["payload"]!!)
            val repeatIndex = obj["repeatIndex"]?.jsonPrimitive?.int
            val node = findNode(inputs.document.root, nodeId) ?: error("node not found in document.root: $nodeId")
            var locals: Locals? = Locals("event", payload, null)
            if (node.rep != null && repeatIndex != null) {
                val items = (interp.eval(node.rep.over, null) as? Value.ListV)?.items
                val item = items?.getOrNull(repeatIndex) ?: Value.Null
                locals = locals.bind(node.rep.asName, item).bind(node.rep.indexName, Value.Num(repeatIndex.toDouble()))
            }
            interp.runStatements(node.on[eventName] ?: emptyList(), locals)
        } else {
            val handlerName = obj["handler"]!!.jsonPrimitive.content
            val args = (obj["args"] as JsonArray).map { Value.fromJson(it) }
            interp.run(handlerName, args)
        }

        assertTrue(sink.errors.isEmpty(), "unexpected interpreter error(s): ${sink.errors}")

        val expect = obj["expect"]!!.jsonObject
        for ((key, expectedJson) in expect["state"]!!.jsonObject) {
            val expected = Value.fromJson(expectedJson)
            val actual = scope.state(key)
            assertTrue(deepEqualsWithTolerance(actual, expected), "state.$key: expected $expected, got $actual")
        }
        val expectEffects = (expect["effects"] as JsonArray).map { Value.fromJson(it) }
        val ok = expectEffects.size == sink.effects.size &&
            expectEffects.indices.all { deepEqualsWithTolerance(sink.effects[it], expectEffects[it]) }
        assertTrue(ok, "effects: expected $expectEffects, got ${sink.effects}")
    }

    private fun runTimelineVector(obj: JsonObject) {
        val timeline = Document.decodeTimeline(obj["timeline"]!!.jsonObject)
        for (sampleEl in obj["samples"]!!.jsonArray) {
            val sample = sampleEl.jsonObject
            val t = sample["t"]!!.jsonPrimitive.double
            val index = sample["index"]!!.jsonPrimitive.int
            val actual = TimelineSampler.sample(timeline, t, index)
            for ((key, expectedEl) in sample["expect"]!!.jsonObject) {
                val expected = expectedEl.jsonPrimitive.double
                val got = actual[key] ?: Double.NaN
                assertTrue(abs(got - expected) < 1e-6, "$key at t=$t index=$index: expected $expected, got $got")
            }
        }
    }

    private fun findNode(node: Node, id: String): Node? {
        if (node.id == id) return node
        for (child in node.children) findNode(child, id)?.let { return it }
        return null
    }

    /** Records — key set + values (order-insensitive); numbers — 1e-9 tolerance, relative for |x| > 1 (README harness rule 2). */
    private fun deepEqualsWithTolerance(a: Value, b: Value): Boolean = when {
        a is Value.Num && b is Value.Num -> numbersClose(a.value, b.value)
        a is Value.ListV && b is Value.ListV ->
            a.items.size == b.items.size && a.items.indices.all { deepEqualsWithTolerance(a.items[it], b.items[it]) }
        a is Value.Rec && b is Value.Rec ->
            a.fields.keys == b.fields.keys && a.fields.keys.all { deepEqualsWithTolerance(a.fields.getValue(it), b.fields.getValue(it)) }
        else -> a == b
    }

    private fun numbersClose(a: Double, b: Double): Boolean {
        if (a == b) return true
        if (a.isNaN() || b.isNaN()) return false
        val tol = if (abs(a) > 1) 1e-9 * abs(a) else 1e-9
        return abs(a - b) <= tol
    }
}
